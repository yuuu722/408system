def expand_entity(name: str) -> list:
    """实体扩展：返回相关节点名列表"""
    key = name.strip()
    result = []
    if key in ENTITY_EXPAND:
        result.extend(ENTITY_EXPAND[key])
    low = key.lower()
    if low in ENTITY_EXPAND:
        result.extend(ENTITY_EXPAND[low])
    # 去重
    seen = set()
    out = []
    for t in result:
        if t not in seen:
            seen.add(t)
            out.append(t)
    return out
